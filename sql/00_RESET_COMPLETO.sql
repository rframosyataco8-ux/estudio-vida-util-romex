CREATE TABLE dbo.Productos (
  Id        INT IDENTITY(1,1) PRIMARY KEY,
  Codigo    VARCHAR(50)  NOT NULL UNIQUE,
  Nombre    NVARCHAR(120) NOT NULL,
  Lote      VARCHAR(30)  NOT NULL,
  Activo    BIT NOT NULL CONSTRAINT DF_Prod_Activo DEFAULT (1),
  CreadoEn  DATETIME2 NOT NULL CONSTRAINT DF_Prod_Creado DEFAULT (SYSUTCDATETIME())
);
GO

CREATE TABLE dbo.ResultadosMicro (
  Id               INT IDENTITY(1,1) PRIMARY KEY,
  ProductoId       INT NOT NULL REFERENCES dbo.Productos(Id),
  Anio             INT NOT NULL,
  Mes              INT NOT NULL CHECK (Mes BETWEEN 1 AND 12),
  FechaAnalisis    DATE NULL,
  RTAMV            INT NOT NULL CONSTRAINT DF_M_RTAMV DEFAULT (0),
  Mohos            INT NOT NULL CONSTRAINT DF_M_Mohos DEFAULT (0),
  Coliformes       INT NOT NULL CONSTRAINT DF_M_Col DEFAULT (0),
  EColi            INT NOT NULL CONSTRAINT DF_M_EC DEFAULT (0),
  Enterobacterias  INT NOT NULL CONSTRAINT DF_M_Ent DEFAULT (0),
  Levaduras        INT NOT NULL CONSTRAINT DF_M_Lev DEFAULT (0),
  SAureus          INT NOT NULL CONSTRAINT DF_M_SA DEFAULT (0),
  Estado           VARCHAR(20) NOT NULL CONSTRAINT DF_M_Est DEFAULT ('LIBERADO'),
  Analista         NVARCHAR(80) NULL,
  LiberadoPor      NVARCHAR(80) NULL,
  Notas            NVARCHAR(500) NULL,
  ActualizadoEn    DATETIME2 NOT NULL CONSTRAINT DF_M_Upd DEFAULT (SYSUTCDATETIME()),
  CONSTRAINT UQ_Micro_Prod_Mes UNIQUE (ProductoId, Anio, Mes)
);
GO

CREATE TABLE dbo.ResultadosFisico (
  Id            INT IDENTITY(1,1) PRIMARY KEY,
  ProductoId    INT NOT NULL REFERENCES dbo.Productos(Id),
  Anio          INT NOT NULL,
  Mes           INT NOT NULL CHECK (Mes BETWEEN 1 AND 12),
  FechaAnalisis DATE NULL,
  Humedad       DECIMAL(8,2) NULL,
  PH            DECIMAL(6,2) NULL,
  Ceniza        DECIMAL(8,2) NULL,
  Grasa         DECIMAL(8,2) NULL,
  Fineza        DECIMAL(8,2) NULL,
  Acidez        DECIMAL(8,2) NULL,
  Estado        VARCHAR(20) NOT NULL CONSTRAINT DF_F_Est DEFAULT ('CONFORME'),
  Analista      NVARCHAR(80) NULL,
  Notas         NVARCHAR(500) NULL,
  ActualizadoEn DATETIME2 NOT NULL CONSTRAINT DF_F_Upd DEFAULT (SYSUTCDATETIME()),
  CONSTRAINT UQ_Fisico_Prod_Mes UNIQUE (ProductoId, Anio, Mes)
);
GO

CREATE INDEX IX_Micro_AnioMes ON dbo.ResultadosMicro(Anio, Mes);
CREATE INDEX IX_Fisico_AnioMes ON dbo.ResultadosFisico(Anio, Mes);
GO

